# Phân loại các bài toán Machine Learning:

# 1. Dự đoán giá nhà dựa trên diện tích.
# -> Thuộc nhóm: Supervised (Có giám sát) - Vì có dữ liệu đầu vào (diện tích) và nhãn mục tiêu đầu ra (giá nhà).

# 2. Gom nhóm khách hàng dựa trên hành vi mua sắm.
# -> Thuộc nhóm: Unsupervised (Không giám sát) - Vì dữ liệu không có nhãn trước, thuật toán tự phân cụm khách hàng dựa trên đặc điểm tương đồng.

# 3. Phân loại email là Spam hay không.
# -> Thuộc nhóm: Supervised (Có giám sát) - Vì dữ liệu đã được gán nhãn sẵn là "Spam" hoặc "Không Spam".

# 4. Nhận diện chữ viết tay từ hình ảnh.
# -> Thuộc nhóm: Supervised (Có giám sát) - Vì mỗi hình ảnh chữ viết tay đi kèm với nhãn nhãn ứng với ký tự thực tế của nó.